//
// ヘソ入賞時（特図1）の振り分け:
//   ・10R大当り×2回（約3000個）電サポ10000回or転落まで … 20.0%
//   ・3R大当り（約450個）電サポ10000回or転落まで        … 40.0%
//   ・3R大当り（約450個）電サポ0回                      … 40.0%
//   20.0+40.0=60.0% がRUSH突入率と一致する。残り40%は電サポが付かず通常へ戻る。
// 電チュー入賞時（特図2）の振り分け:
//   ・10R大当り（約1500個）電サポ10000回or転落まで … 100%
//
// 【この機種がこれまでと違う点】
// RUSHが規定回数で終わらない。「次の大当り(約1/41.1)か転落小当り(約1/153.7)を
// 引くまでループ」する転落抽選型なので、countUp/countDownでは表現できない。
// このためエンジンに onFall を足した（core/stateEngine.js を参照）。
// 電サポ10000回は事実上の無制限なので、maxAttemptsではなくonFallで表現している。
//
// 【継続率が公表値と1.7ポイントずれていた件・解決】
// 大当り/転落の確率だけをそのまま実装すると、RUSH継続率は79.3%になり、
// 1geki.jp掲載の「約81%」と合わなかった。原因は「残保留での引き戻し」を
// 考慮していなかったため。転落を引いた瞬間、始動口には既に4回転ぶんの玉が
// 入っている（残保留）。転落表示が出ても、この4回転はRUSH中の確率(1/41.1)で
// 実際に抽選されており、1回でも当たれば引き戻されてRUSH継続になる。
//   残保留4回転での引き戻し確率 = 1-(1-1/41.1)^4 ≈ 9.3%
//   最終継続率 = 78.9%（大当り2.4338%/転落0.6342%の比率、四捨五入前）
//                + 21.1%（転落）×9.3%（引き戻し）≈ 81.0%
// 1geki.jpの「約81%」はこの残保留の引き戻し込みの数値だった。
// エンジン側にonFall.residualAttemptsを新設し、転落を引いた瞬間に確定させず、
// 残保留4回転ぶん「当たりかどうか」だけを追加判定してから確定させるようにした
// （転落の再抽選はしない。詳細はcore/stateEngine.jsのコメントを参照）。
//
// 【出玉は「実獲得個数」を採用（払い出し基準からの変更）】
// 1geki.jpは払い出し個数と実獲得個数の両方を載せている（10R: 約1500個/実獲得1400個、
// 3R: 約450個/実獲得420個）。当初は払い出し個数（グロス）を採っていたが、ラウンド数の
// 多い機種ほど払い出しと実獲得の差が積み重なって無視できなくなってきたため
// （ガンダムSEEDクライマックスの10R×3=4500個/実獲得4200個など）、依頼者の判断で
// 実獲得個数（ネット、実際に持ち玉へ乗る量）へ切り替えた。ランキングの基準が
// 機種間で混ざらないよう、既存の全機種（このファイル含め5機種）をまとめて直している。
// 以降、新機種を追加するときも実獲得個数で揃えること。
//
// 【入れなかった項目】
// 導入年・カテゴリは、もらったスクリーンショットに写っておらず確認できなかったため
