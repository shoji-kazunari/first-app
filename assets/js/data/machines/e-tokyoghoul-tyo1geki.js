// 「大当り確率：約1/349.9」はあくまで脚注（※1 図柄揃い大当り確率とチャージからの突入
// 大当り確率の合算）で、サイト上も主役ではない。そのためrulesの表記も「約1/999」を
// 前面に出す（シミュレーター内部の1回転あたりのヒット判定は、チャージ分も含めた
// 実際の当選頻度を再現する必要があるため、引き続き合算値1/349.9をstates.normal.
// probabilityに使う。これは表示上の見せ方の話であり、抽選ロジックは変更していない）。
//
// ヘソ入賞時（特図1・通常時）の大当り振り分け（詳細は下の【喰種チャージ】節）:
//   ・図柄揃い(約1/999)：10R大当り×2(約3000個)→通常が50%、10R大当り×5(約7500個)
//     →HYPER喰種RUSH(ST5回)が50%
//   ・喰種チャージ(約1/538.8)：2R大当り(約300個)→通常が99.5%、昇格して
//     10R大当り×5(約7500個)→HYPER喰種RUSH(ST5回)が0.5%（昇格率は依頼者の決めうち。
//     根拠は下の【喰種チャージ】節）
// 電チュー入賞時（特図2・HYPER喰種RUSH中）の振り分け:
//   ・10R×2(約3000個)を基準に、「上乗せ3000ジャッジ」（成功率約50%、
//     1geki.jpのテキストに明記）に成功する限り約3000個ずつ上乗せし続けるループ。
//     円グラフの内訳（3000個50%・6000個25%・9000個12.5%・9000個超12.5%）は
//     50%の等比数列（0.5^0, 0.5^1, 0.5^2, 0.5^2...）と完全に一致するため、
//     stateEngineのbonusLoopプリミティブ（成功する限り繰り返し上乗せ）で
//     そのまま正確に再現できる。SWORD DRIVE（SAO夜空）のような非公開の
//     継続率を推測する必要はなかった。
// 状態遷移: HYPER喰種RUSH全弾外れ（5回転消化）→通常
// （継続率約50%は、大当り確率1/7.7・ST5回から自然に導かれる値と一致 [1-(1-1/7.7)^5≈50%]
// なので、継続率の裏取りにも1geki.jp発表の1/7.7をそのまま使っている）。
//
// 【喰種チャージを独立した分岐として実装した理由・昇格率0.5%の根拠】
// 喰種チャージ（約1/538.8、2R・約300個、消化後の移行先は「昇格発生：約7500個獲得後に
// HYPER喰種RUSH突入／昇格非発生：通常時へ移行」、「大半は通常時へ移行するが、消化中に
// 昇格演出が発生すれば約7500個を獲得してHYPER喰種RUSHに突入」）は、当初は円グラフ
// （図柄揃い時の出玉振り分け50%/50%）へそのまま合流させて実装していたが、依頼者から
// 「当たりよりチャージの方が確率が高い（1/538.8は1/999より頻度が高い）ため、チャージを
// 引く印象の方が強い。体感が変わるのでチャージを独立して再現したい」との指示があり、
// 図柄揃いとチャージを別の分岐として実装し直した。
//
// 喰種チャージ単体の昇格率は1geki.jpに数値の記載が無く（「大半は通常へ」という定性的な
// 表現のみ）、機械的な裏取りができない。図柄揃い単体の昇格率（50%、円グラフで直接公開）と
// スペック表の「トータル突入率約50%（図柄揃い+チャージ合算）」の2つを使って代数的に
// 逆算すると、チャージ単体の昇格率はちょうど50%になる（重み付き平均が一方の値と完全一致
// する場合、もう一方も同じ値でないと成立しないため）。しかしこれは「大半は通常へ」という
// 本文の記述と食い違う（50%なら"大半"とは言えない）。依頼者と相談した結果、
// 「大半は通常へ」を優先し、チャージ単体の昇格率は依頼者の決めうちで0.5%とする（この
// 場合、シミュレーター上のトータル突入率は1geki.jp公表の約50%より低い約17.8%になる。
// 図柄揃い(1/999)とチャージ(1/538.8)の出現比率が約35:65でチャージの方が多いため、
// チャージの昇格率を大きく下げると合算のトータル突入率も大きく下がる。1geki.jp公表の
// 「トータル突入率約50%」と実装値が食い違うのは把握した上での依頼者の判断であり、
// 実装ミスではない）。
//
// 図柄揃い(1/999)とチャージ(1/538.8)の出現比率（35.04%:64.96%）に、それぞれの
// 昇格率（図柄揃い50%、チャージ0.5%）を掛け合わせた重みを、states.normal.onHit.
// outcomesの4分岐（図柄揃い→通常/図柄揃い→RUSH/チャージ→通常/チャージ→RUSH）の
